/**
 * Helper to process, extract, and normalize image assets from project state and inline data URIs.
 */
export function extractAndPrepareImagesForExport(
  project: EbookProject
): {
  imageAssets: Array<{
    id: string;
    filename: string;
    href: string;
    mimeType: string;
    base64Data: string;
    dataUrl: string;
    isCover: boolean;
  }>;
  dataUrlToHrefMap: Record<string, string>;
} {
  const imageAssets: Array<{
    id: string;
    filename: string;
    href: string;
    mimeType: string;
    base64Data: string;
    dataUrl: string;
    isCover: boolean;
  }> = [];

  const dataUrlToHrefMap: Record<string, string> = {};
  const processedDataUrls = new Set<string>();

  let imgCounter = 1;

  if (project.images) {
    for (const [key, dataUrl] of Object.entries(project.images)) {
      if (!dataUrl || typeof dataUrl !== 'string' || processedDataUrls.has(dataUrl)) continue;

      let mimeType = 'image/jpeg';
      const mimeMatch = dataUrl.match(/^data:([^;]+);/);
      if (mimeMatch) {
        mimeType = mimeMatch[1];
      }

      let ext = 'jpg';
      if (mimeType.includes('png')) ext = 'png';
      else if (mimeType.includes('gif')) ext = 'gif';
      else if (mimeType.includes('svg')) ext = 'svg';
      else if (mimeType.includes('webp')) ext = 'webp';

      let filename = key.split('/').pop() || `image_${imgCounter}.${ext}`;
      if (!filename.includes('.')) filename += `.${ext}`;

      const href = `images/${filename}`;
      const base64Data = dataUrl.replace(/^data:[^;]+;base64,/, '').trim();
      const isCover = key.toLowerCase().includes('cover') || filename.toLowerCase().includes('cover') || imgCounter === 1;

      const asset = {
        id: `img_${imgCounter++}`,
        filename,
        href,
        mimeType,
        base64Data,
        dataUrl,
        isCover
      };

      imageAssets.push(asset);
      dataUrlToHrefMap[dataUrl] = href;
      processedDataUrls.add(dataUrl);
    }
  }

  project.chapters.forEach((ch) => {
    const xhtml = ch.translatedXhtml || ch.originalXhtml;
    const imgRegex = /src=["'](data:image\/[^"']+)["']/gi;
    let match;
    while ((match = imgRegex.exec(xhtml)) !== null) {
      const dataUrl = match[1];
      if (processedDataUrls.has(dataUrl)) continue;

      let mimeType = 'image/jpeg';
      const mimeMatch = dataUrl.match(/^data:([^;]+);/);
      if (mimeMatch) {
        mimeType = mimeMatch[1];
      }

      let ext = 'jpg';
      if (mimeType.includes('png')) ext = 'png';
      else if (mimeType.includes('gif')) ext = 'gif';
      else if (mimeType.includes('svg')) ext = 'svg';
      else if (mimeType.includes('webp')) ext = 'webp';

      const filename = `image_${imgCounter}.${ext}`;
      const href = `images/${filename}`;
      const base64Data = dataUrl.replace(/^data:[^;]+;base64,/, '').trim();
      const isCover = imgCounter === 1;

      const asset = {
        id: `img_${imgCounter++}`,
        filename,
        href,
        mimeType,
        base64Data,
        dataUrl,
        isCover
      };

      imageAssets.push(asset);
      dataUrlToHrefMap[dataUrl] = href;
      processedDataUrls.add(dataUrl);
    }
  });

  return { imageAssets, dataUrlToHrefMap };
}

/**
 * Custom Ebook Exporter supporting PDF, TXT, EPUB, EPUB3, KPUB, XHTML, MOBI with annotations and image repacking
 */
export async function exportEbookCustom(
  project: EbookProject,
  options: {
    fileName: string;
    format: 'epub' | 'epub3' | 'pdf' | 'txt' | 'kpub' | 'xhtml' | 'mobi';
    includeAnnotations: boolean;
    selectedAnnotations: any[];
    annotationsPlacement: 'endnotes' | 'inline' | 'preamble';
  }
): Promise<void> {
  const { fileName, format, includeAnnotations, selectedAnnotations, annotationsPlacement } = options;

  const { imageAssets, dataUrlToHrefMap } = extractAndPrepareImagesForExport(project);

  const rewriteXhtmlImageSources = (xhtml: string): string => {
    let rewritten = xhtml;
    for (const [dataUrl, href] of Object.entries(dataUrlToHrefMap)) {
      rewritten = rewritten.split(dataUrl).join(href);
    }
    return rewritten;
  };

  // Build annotations XHTML block
  let annotationsHtml = '';
  if (includeAnnotations && selectedAnnotations.length > 0) {
    annotationsHtml = `\n<div class="annotations-section" id="book-annotations">
      <h2 class="annotations-heading">Annotations & Scholarly Footnotes</h2>
      <ol class="annotations-list">`;
    selectedAnnotations.forEach((ann, idx) => {
      annotationsHtml += `\n  <li id="ann-${idx + 1}" class="annotation-item">
    <strong>[${idx + 1}] ${ann.title}</strong> (${ann.type}): 
    <em>"${ann.selectedText}"</em> — ${ann.explanationOrDefinition}
    ${ann.historicalDetails ? `<br/><small class="historical-note">Historical Context: ${ann.historicalDetails}</small>` : ''}
  </li>`;
    });
    annotationsHtml += `\n</ol>\n</div>`;
  }

  // Handle TXT Format
  if (format === 'txt') {
    let txtContent = `${project.title.toUpperCase()}\nBy ${project.author}\nLanguage: Modern English Translation\n${'='.repeat(50)}\n\n`;
    
    project.chapters.forEach((ch, idx) => {
      let rawText = ch.translatedXhtml || ch.originalXhtml;
      rawText = rawText.replace(/<img[^>]+alt=["']([^"']+)["'][^>]*>/gi, '[Illustration: $1]');
      rawText = rawText.replace(/<img[^>]*>/gi, '[Embedded Illustration]');
      const cleanText = rawText.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
      txtContent += `CHAPTER ${idx + 1}: ${ch.title.toUpperCase()}\n${'-'.repeat(40)}\n${cleanText}\n\n`;
    });

    if (includeAnnotations && selectedAnnotations.length > 0) {
      txtContent += `\n${'='.repeat(50)}\nANNOTATIONS & FOOTNOTES\n${'='.repeat(50)}\n\n`;
      selectedAnnotations.forEach((ann, idx) => {
        txtContent += `[${idx + 1}] ${ann.title} (${ann.type})\nText: "${ann.selectedText}"\nNote: ${ann.explanationOrDefinition}\n${ann.historicalDetails ? `History: ${ann.historicalDetails}\n` : ''}\n`;
      });
    }

    const blob = new Blob([txtContent], { type: 'text/plain;charset=utf-8' });
    downloadBlob(blob, `${fileName}.txt`);
    return;
  }

  // Handle PDF Format
  if (format === 'pdf') {
    const doc = new jsPDF({ unit: 'pt', format: 'letter' });
    let y = 50;

    doc.setFont('times', 'bold');
    doc.setFontSize(22);
    doc.text(project.title, 40, y);

    y += 24;
    doc.setFontSize(12);
    doc.setFont('times', 'italic');
    doc.text(`By ${project.author} — Modern English Edition`, 40, y);

    y += 40;

    project.chapters.forEach((ch, idx) => {
      if (y > 700) {
        doc.addPage();
        y = 50;
      }

      doc.setFont('times', 'bold');
      doc.setFontSize(14);
      doc.text(`Chapter ${idx + 1}: ${ch.title}`, 40, y);
      y += 20;

      doc.setFont('times', 'normal');
      doc.setFontSize(10);
      const cleanText = (ch.translatedXhtml || ch.originalXhtml).replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
      const lines = doc.splitTextToSize(cleanText, 520);

      lines.forEach((line: string) => {
        if (y > 740) {
          doc.addPage();
          y = 50;
        }
        doc.text(line, 40, y);
        y += 14;
      });

      // Embed repacked images into PDF
      imageAssets.forEach((img) => {
        if (img.dataUrl && y < 620) {
          try {
            const imgType = img.mimeType.includes('png') ? 'PNG' : 'JPEG';
            doc.addImage(img.dataUrl, imgType, 40, y, 220, 150);
            y += 160;
          } catch (err) {
            console.warn('[PDF Image Embed Warning]', err);
          }
        }
      });

      y += 25;
    });

    if (includeAnnotations && selectedAnnotations.length > 0) {
      if (y > 650) {
        doc.addPage();
        y = 50;
      }
      doc.setFont('times', 'bold');
      doc.setFontSize(16);
      doc.text('Annotations & Footnotes', 40, y);
      y += 25;

      selectedAnnotations.forEach((ann, idx) => {
        if (y > 720) {
          doc.addPage();
          y = 50;
        }
        doc.setFont('times', 'bold');
        doc.setFontSize(10);
        doc.text(`[${idx + 1}] ${ann.title} (${ann.type})`, 40, y);
        y += 14;

        doc.setFont('times', 'normal');
        const noteText = `Selected: "${ann.selectedText}" — ${ann.explanationOrDefinition}`;
        const noteLines = doc.splitTextToSize(noteText, 500);
        noteLines.forEach((l: string) => {
          if (y > 740) {
            doc.addPage();
            y = 50;
          }
          doc.text(l, 50, y);
          y += 12;
        });
        y += 10;
      });
    }

    doc.save(`${fileName}.pdf`);
    return;
  }

  // Handle EPUB / EPUB3 / KPUB / MOBI / XHTML (ZIP Bundle Generation)
  const zip = new JSZip();

  if (format === 'xhtml') {
    // Pack image assets into images/ folder inside zip
    imageAssets.forEach((img) => {
      if (img.mimeType === 'image/svg+xml' && img.dataUrl.includes('utf8,')) {
        const svgText = decodeURIComponent(img.dataUrl.split('utf8,')[1]);
        zip.file(img.href, svgText);
      } else {
        zip.file(img.href, img.base64Data, { base64: true });
      }
    });

    project.chapters.forEach((ch, idx) => {
      let chContent = rewriteXhtmlImageSources(ch.translatedXhtml || ch.originalXhtml);
      if (includeAnnotations && selectedAnnotations.length > 0 && annotationsPlacement === 'endnotes' && idx === project.chapters.length - 1) {
        chContent += annotationsHtml;
      }

      zip.file(`chapter_${idx + 1}.xhtml`, `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.1//EN" "http://www.w3.org/TR/xhtml11/DTD/xhtml11.dtd">
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
  <meta http-equiv="Content-Type" content="application/xhtml+xml; charset=utf-8"/>
  <title>${ch.title}</title>
  <style>${project.cssContent}</style>
</head>
<body>${chContent}</body>
</html>`);
    });

    const blob = await zip.generateAsync({ type: 'blob' });
    downloadBlob(blob, `${fileName}_xhtml_bundle.zip`);
    return;
  }

  // For EPUB 2.0, EPUB 3.2, KPUB, MOBI: Build complete EPUB container structure
  zip.file('mimetype', 'application/epub+zip', { compression: 'STORE' });
  const metaInf = zip.folder('META-INF')!;
  metaInf.file('container.xml', `<?xml version="1.0"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
   <rootfiles>
      <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
   </rootfiles>
</container>`);

  const oebps = zip.folder('OEBPS')!;
  oebps.file('style.css', project.cssContent || 'body { font-family: serif; line-height: 1.6; padding: 1.2em; color: #111; }');

  // Pack binary image files into OEBPS/images/
  imageAssets.forEach((img) => {
    if (img.mimeType === 'image/svg+xml' && img.dataUrl.includes('utf8,')) {
      const svgText = decodeURIComponent(img.dataUrl.split('utf8,')[1]);
      oebps.file(img.href, svgText);
    } else {
      oebps.file(img.href, img.base64Data, { base64: true });
    }
  });

  const isEpub3 = format === 'epub3' || format === 'kpub';
  const isKpub = format === 'kpub';
  const isMobi = format === 'mobi';

  // Process Chapter XHTML Files with rewritten image src paths
  project.chapters.forEach((ch, idx) => {
    let chContent = rewriteXhtmlImageSources(ch.translatedXhtml || ch.originalXhtml);
    if (includeAnnotations && selectedAnnotations.length > 0 && annotationsPlacement === 'inline') {
      chContent += annotationsHtml;
    }

    // Wrap paragraphs with Kobo spans for KPUB format
    if (isKpub) {
      let pCounter = 1;
      chContent = chContent.replace(/<p([^>]*)>(.*?)<\/p>/gi, (_match, attrs, innerText) => {
        const spanId = `kobo.${idx + 1}.${pCounter++}`;
        return `<p${attrs}><span class="koboSpan" id="${spanId}">${innerText}</span></p>`;
      });
    }

    const docTypeHeader = isEpub3
      ? `<!DOCTYPE html>`
      : `<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.1//EN" "http://www.w3.org/TR/xhtml11/DTD/xhtml11.dtd">`;

    const htmlNs = isEpub3
      ? `<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="en" lang="en">`
      : `<html xmlns="http://www.w3.org/1999/xhtml" xml:lang="en">`;

    const headCharset = isEpub3
      ? `<meta charset="utf-8"/><meta name="viewport" content="width=device-width, initial-scale=1.0"/>`
      : `<meta http-equiv="Content-Type" content="application/xhtml+xml; charset=utf-8"/>`;

    const fullXhtml = `<?xml version="1.0" encoding="utf-8"?>
${docTypeHeader}
${htmlNs}
<head>
  ${headCharset}
  <title>${ch.title}</title>
  <link rel="stylesheet" href="style.css" type="text/css"/>
</head>
<body>
${chContent}
</body>
</html>`;

    oebps.file(`chapter_${idx + 1}.xhtml`, fullXhtml);
  });

  // Endnotes Chapter if selected
  if (includeAnnotations && selectedAnnotations.length > 0 && annotationsPlacement === 'endnotes') {
    const endnotesXhtml = `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xml:lang="en">
<head>
  <meta charset="utf-8"/>
  <title>Annotations & Footnotes</title>
  <link rel="stylesheet" href="style.css" type="text/css"/>
</head>
<body>
${annotationsHtml}
</body>
</html>`;
    oebps.file('annotations.xhtml', endnotesXhtml);
  }

  // Build NCX Table of Contents (toc.ncx) - Required for EPUB2, MOBI, and fallback for EPUB3
  let ncxPoints = '';
  let playOrder = 1;

  project.chapters.forEach((ch, idx) => {
    ncxPoints += `    <navPoint id="navPoint-${playOrder}" playOrder="${playOrder}">
      <navLabel><text>${ch.title}</text></navLabel>
      <content src="chapter_${idx + 1}.xhtml"/>
    </navPoint>\n`;
    playOrder++;
  });

  if (includeAnnotations && selectedAnnotations.length > 0 && annotationsPlacement === 'endnotes') {
    ncxPoints += `    <navPoint id="navPoint-${playOrder}" playOrder="${playOrder}">
      <navLabel><text>Annotations & Footnotes</text></navLabel>
      <content src="annotations.xhtml"/>
    </navPoint>\n`;
  }

  const tocNcx = `<?xml version="1.0" encoding="UTF-8"?>
<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1">
  <head>
    <meta name="dtb:uid" content="urn:uuid:verba-nova-ii-${project.id}"/>
    <meta name="dtb:depth" content="1"/>
    <meta name="dtb:totalPageCount" content="0"/>
    <meta name="dtb:maxPageNumber" content="0"/>
  </head>
  <docTitle><text>${project.title}</text></docTitle>
  <docAuthor><text>${project.author}</text></docAuthor>
  <navMap>
${ncxPoints}  </navMap>
</ncx>`;

  oebps.file('toc.ncx', tocNcx);

  // Build EPUB 3 Navigation Document (toc.xhtml) - Required for EPUB 3.2 and KPUB
  let navItems = '';
  project.chapters.forEach((ch, idx) => {
    navItems += `        <li><a href="chapter_${idx + 1}.xhtml">${ch.title}</a></li>\n`;
  });
  if (includeAnnotations && selectedAnnotations.length > 0 && annotationsPlacement === 'endnotes') {
    navItems += `        <li><a href="annotations.xhtml">Annotations & Footnotes</a></li>\n`;
  }

  const tocXhtml = `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="en" lang="en">
<head>
  <meta charset="utf-8"/>
  <title>Table of Contents</title>
  <link rel="stylesheet" href="style.css" type="text/css"/>
</head>
<body>
  <nav epub:type="toc" id="toc">
    <h2>Table of Contents</h2>
    <ol>
${navItems}    </ol>
  </nav>
</body>
</html>`;

  if (isEpub3) {
    oebps.file('toc.xhtml', tocXhtml);
  }

  // Build Manifest & OPF Package metadata
  let manifestItems = '<item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>\n';
  manifestItems += '<item id="css" href="style.css" media-type="text/css"/>\n';

  if (isEpub3) {
    manifestItems += '<item id="toc" href="toc.xhtml" media-type="application/xhtml+xml" properties="nav"/>\n';
  }

  // Include repacked image assets in OPF Manifest
  imageAssets.forEach((img) => {
    const coverProp = isEpub3 && img.isCover ? ' properties="cover-image"' : '';
    manifestItems += `<item id="${img.id}" href="${img.href}" media-type="${img.mimeType}"${coverProp}/>\n`;
  });

  let spineItems = '';

  project.chapters.forEach((_, idx) => {
    manifestItems += `<item id="ch${idx + 1}" href="chapter_${idx + 1}.xhtml" media-type="application/xhtml+xml"/>\n`;
    spineItems += `    <itemref idref="ch${idx + 1}"/>\n`;
  });

  if (includeAnnotations && selectedAnnotations.length > 0 && annotationsPlacement === 'endnotes') {
    manifestItems += `<item id="annotations" href="annotations.xhtml" media-type="application/xhtml+xml"/>\n`;
    spineItems += `    <itemref idref="annotations"/>\n`;
  }

  const opfVersion = isEpub3 ? '3.0' : '2.0';
  const timestampIso = new Date().toISOString().replace(/\.\d+Z$/, 'Z');

  let advancedMetaTags = '';
  if (isEpub3) {
    advancedMetaTags += `<meta property="dcterms:modified">${timestampIso}</meta>\n`;
    advancedMetaTags += `<meta property="rendition:layout">reflowable</meta>\n`;
    advancedMetaTags += `<meta property="rendition:orientation">auto</meta>\n`;
    advancedMetaTags += `<meta property="rendition:spread">auto</meta>\n`;
    advancedMetaTags += `<meta property="ibooks:specified-fonts">true</meta>\n`;
    advancedMetaTags += `<meta name="primary-writing-mode" content="horizontal-lr"/>\n`;
  }

  if (isKpub) {
    advancedMetaTags += `<meta property="kobo:meta">kepub-converted</meta>\n`;
  }

  if (isMobi) {
    advancedMetaTags += `<meta name="cover" content="cover-image"/>\n`;
    advancedMetaTags += `<meta name="book-type" content="book"/>\n`;
    advancedMetaTags += `<meta name="orientation-lock" content="none"/>\n`;
  }

  const opf = `<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" unique-identifier="BookID" version="${opfVersion}">
    <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
        <dc:identifier id="BookID">urn:uuid:verba-nova-ii-${project.id}</dc:identifier>
        <dc:title>${project.title} (Modern English Edition)</dc:title>
        <dc:creator>${project.author}</dc:creator>
        <dc:language>en</dc:language>
        <dc:publisher>Verba Nova II — Illuminated Adaptive E-Works</dc:publisher>
        <dc:date>${new Date().toISOString().split('T')[0]}</dc:date>
        <dc:description>${project.description || 'Tag-Preserving Modern English Translation'}</dc:description>
        ${advancedMetaTags}
    </metadata>
    <manifest>
        ${manifestItems}    </manifest>
    <spine toc="ncx">
    ${spineItems}    </spine>
</package>`;

  oebps.file('content.opf', opf);

  const zipBlob = await zip.generateAsync({ type: 'blob' });

  let extension = '.epub';
  if (format === 'epub3') extension = '.epub';
  if (format === 'kpub') extension = '.kepub.epub';
  if (format === 'mobi') extension = '.mobi';

  downloadBlob(zipBlob, `${fileName}${extension}`);
}

/**
 * Exports a single completed section/chapter in XHTML, TXT, or HTML format directly
 */
export function exportSingleChapter(
  chapter: { title: string; translatedXhtml?: string; originalXhtml: string },
  projectTitle: string,
  format: 'xhtml' | 'txt' | 'html' = 'xhtml'
) {
  const content = chapter.translatedXhtml || chapter.originalXhtml;
  const safeTitle = chapter.title.replace(/[^a-z0-9_-]/gi, '_');

  if (format === 'txt') {
    const plainText = content.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
    const blob = new Blob([`${chapter.title}\n${'='.repeat(chapter.title.length)}\n\n${plainText}`], { type: 'text/plain;charset=utf-8' });
    downloadBlob(blob, `${projectTitle}_${safeTitle}.txt`);
    return;
  }

  const fullXhtml = `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.1//EN" "http://www.w3.org/TR/xhtml11/DTD/xhtml11.dtd">
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
  <meta http-equiv="Content-Type" content="application/xhtml+xml; charset=utf-8"/>
  <title>${chapter.title}</title>
</head>
<body>
${content}
</body>
</html>`;

  const blob = new Blob([fullXhtml], { type: 'application/xhtml+xml;charset=utf-8' });
  downloadBlob(blob, `${projectTitle}_${safeTitle}.xhtml`);
}

function downloadBlob(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.click();
  URL.revokeObjectURL(url);
}
